/// Кодирование строки в Windows-1251.
///
/// ЗАЧЕМ ЭТО НА КЛИЕНТЕ
///     QR оплаты по ГОСТ Р 56042-2014 обязан несть байты в той
///     кодировке, которую объявляет маркер `ST0001X` (1 — Windows-1251,
///     2 — UTF-8, 3 — KOI8-R). Банковское приложение читает именно
///     байты, а `QrImageView(data: строка)` из qr_flutter прогоняет её
///     через `utf8.encode` — в код попадает UTF-8 вопреки маркеру, и
///     Сбербанк показывает каракули («Р”Р°РіРµСЃС‚Р°РЅ» вместо
///     «Дагестан»).
///
///     Бэкенд отдаёт готовые байты полем `qr_bytes`, но полагаться
///     только на него нельзя: при старом сервере, пустом поле или
///     ошибке разбора клиент молча рисовал UTF-8 QR — ровно ту
///     картинку, из-за которой платёж не проходил. Своё кодирование
///     убирает эту зависимость: QR правильный даже со старым бэкендом.
///
/// Dart не умеет CP1251 из коробки (`dart:convert` знает только
/// ASCII/Latin-1/UTF-8), поэтому таблица задана здесь.
library;

import 'dart:typed_data';

/// Символы вне ASCII и русского алфавита, встречающиеся в реквизитах.
const Map<int, int> _extra = {
  0x0401: 0xA8, // Ё
  0x0451: 0xB8, // ё
  0x2116: 0xB9, // № — есть в адресах и названиях отделений банка
  0x00A0: 0xA0, // неразрывный пробел
  0x00AB: 0xAB, // «
  0x00BB: 0xBB, // »
  0x2013: 0x96, // –
  0x2014: 0x97, // —
  0x2018: 0x91, // '
  0x2019: 0x92, // '
  0x201C: 0x93, // "
  0x201D: 0x94, // "
  0x201E: 0x84, // „
  0x2026: 0x85, // …
  0x00B0: 0xB0, // °
  0x00A9: 0xA9, // ©
  0x2022: 0x95, // •
  0x0490: 0xA5, // Ґ
  0x0491: 0xB4, // ґ
  0x0404: 0xAA, // Є
  0x0454: 0xBA, // є
  0x0407: 0xAF, // Ї
  0x0457: 0xBF, // ї
  0x0406: 0xB2, // І
  0x0456: 0xB3, // і
};

/// Байт-заменитель для символов, которых нет в CP1251.
///
/// Как `errors="replace"` в Python: теряется один символ, а не весь
/// текст. Реквизиты и сумма при этом читаются, и платёж проходит.
const int _replacement = 0x3F; // '?'

/// Строка → байты Windows-1251.
Uint8List cp1251Encode(String input) {
  final out = Uint8List(input.runes.length);
  var i = 0;
  for (final rune in input.runes) {
    if (rune < 0x80) {
      // ASCII совпадает с CP1251 один в один.
      out[i++] = rune;
    } else if (rune >= 0x0410 && rune <= 0x044F) {
      // А-я идут непрерывно: U+0410..U+044F → 0xC0..0xFF.
      out[i++] = rune - 0x0410 + 0xC0;
    } else {
      out[i++] = _extra[rune] ?? _replacement;
    }
  }
  return out;
}
